  function testDatesOf(round, rollout) {
    const raw = [];
    const seen = new Set();
    const add = (d) => { if (d && d.iso && !seen.has(d.iso)) { seen.add(d.iso); raw.push(d); } };
    for (const it of round.items) {
      if (it.kind !== "cryo_complete" && it.kind !== "cryo_test") continue;
      add(it.date);
      for (const f of it.group || []) {
        if (f.eventDate && (f.kindEvent === "cryo_complete" || f.kindEvent === "cryo_test")) add(f.eventDate);
      }
    }
    raw.sort((a, b) => a.iso.localeCompare(b.iso));
    const returnDays = new Set(round.items.filter((it) => it.kind === "return" || it.kind === "return_engines" || it.kind === "no_visible").map((it) => it.date && it.date.iso).filter(Boolean));
    const withoutReturn = raw.filter((d) => !returnDays.has(d.iso));
    const use = withoutReturn.length ? withoutReturn : raw;
    const later = use.filter((d) => !rollout || d.iso > rollout.iso);
    return later.length ? later : use;
  }
