  function clusterRounds(entries) {
    entries = entries.slice().sort((a, b) => String(a.iso || "").localeCompare(String(b.iso || "")) || String(a.date || "").localeCompare(String(b.date || "")));
    const rounds = [];
    let cur = null, prevIso = null;
    for (const e of entries) {
      const gap = prevIso && e.iso ? (Date.parse(e.iso) - Date.parse(prevIso)) / 864e5 : 0;
      if (!cur || gap > 5) { cur = { items: [] }; rounds.push(cur); }
      cur.items.push(e);
      prevIso = e.iso || prevIso;
    }
    return rounds;
  }
  function leadEntry(items) {
    const score = (e) => {
      const t = e.text || "";
      if (/\bcomplet(?:ed|e)\b|\bfired\b|static fire|stacked|licence issued|approval has arrived|launched/i.test(t)) return 5;
      if (/roll(?:ed|ing) out|arrived|lifted|returned/i.test(t)) return 3;
      if (/prepar/i.test(t)) return 1;
      return 2;
    };
    return items.slice().sort((a, b) => score(b) - score(a) || String(b.iso || "").localeCompare(String(a.iso || "")))[0];
  }
