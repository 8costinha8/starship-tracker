  function sourceHandleOf(link) {
    if (!link) return "";
    const url = link.url || "";
    const article = link.kind === "article" || link.dateOnly || (url && !/x\.com|twitter\.com/i.test(url) && /\.(com|net|org)\//i.test(url));
    if (article) return displaySource(link);
    const h = String(link.handle || "").replace(/^@/, "");
    return h ? "@" + h : displaySource(link);
  }
  function saysEnginesInstalled(t) {
    const s = String(t || "");
    if (/due to receive|ahead of engine|for engine installation|being reinstalled|headed back for|removed from|will now receive/i.test(s)) return false;
    return /ready with all\s*\d+\s*raptors|raptors were all in|all (?:six|6|33) raptors\b[\s\S]*\b(?:in|installed)|engines are installed|installed (?:all )?(?:its |the )?(?:six |6 |33 )?raptors/i.test(s);
  }
  function eventBoxOf(box, text) {
    const t = String(text || "");
    if (box === "static" && /heads? back after pad activity|pad activity at Pad/i.test(t) && !/static fire/i.test(t)) return "pad";
    return box;
  }
  function tidyPadPillText(text, url) {
    const t = String(text || "").replace(/\s+/g, " ").trim();
    // Verbatim source (Blobifie 2115205843880992791): "SpaceX completed post catch pusher testing with S43 with this test going much smoother than when it was done with S42!"
    // S43 has not flown: drop "post-catch" even though the source used that phrase.
    if (/pusher test/i.test(t) && /S43|Ship 43/.test(t)) {
      return "SpaceX completed pusher testing with Ship 43, much smoother than with Ship 42.";
    }
    return t;
  }
  function datePillLabel(start, end, ongoing) {
    if (ongoing && start) return `From ${fmtDay(start)}`;
    if (start && end && start.iso !== end.iso) return spanDays(start, end);
    return fmtDay(start || end) || "";
  }

  function displaySource(link) {
    if (!link) return "";
    const url = link.url || "";
    const outlet = link.outlet || link.handle_or_outlet || "";
    const article = link.kind === "article" || link.dateOnly || (url && !/x\.com|twitter\.com/i.test(url) && /\.(com|net|org)\//i.test(url));
    if (/nasaspaceflight/i.test(url) || /nasaspaceflight/i.test(outlet) || /nasaspaceflight/i.test(link.handle || "")) {
      return article || /nasaspaceflight\.com/i.test(url) || /nasaspaceflight/i.test(outlet) ? "NASASpaceFlight.com" : "NASASpaceFlight.com";
    }
    if (/spacebytes/i.test(url) || /spacebytes/i.test(outlet)) return "SpaceBytes";
    if (/nextspaceflight/i.test(url) || /nextspaceflight/i.test(outlet)) return "Next Spaceflight";
    if (/spaceflightnow/i.test(url) || /spaceflight now/i.test(outlet)) return "Spaceflight Now";
    if (/spacenews/i.test(url)) return "SpaceNews";
    if (article) {
      if (outlet && !/^@/.test(outlet) && !/^https?:/i.test(outlet)) return outlet;
      try { return new URL(url).hostname.replace(/^www\./, ""); } catch (e) {}
    }
    const h = link.handle || "";
    if (h) return h.startsWith("@") ? h : "@" + h.replace(/^@/, "");
    return outlet || "";
  }

  function sourceFromEntry(h) {
    if (!h) return "";
    if (h.review_source) return h.review_source;
    const url = h.url || (h.x_post && h.x_post.url) || "";
    const handle = h.src || (h.x_post && h.x_post.author && (h.x_post.author.username || h.x_post.author)) || "";
    // Never credit a fallback default photo — only the headline / same-source post.
    return displaySource({ url, handle, outlet: h.source, kind: url && !/x\.com|twitter\.com/i.test(url) ? "article" : undefined });
  }
  function writeHistory(road, beatGroups, beats, currentVehicles, log, livePhotos) {
    let changed = false;
    const current = new Set(currentVehicles);
    const byBox = { cryo: [], raptor: [] };
    for (const g of beatGroups) {
      const veh = g[0].vehicle;
      if (!current.has(veh)) continue; // S42 stays in the archive, not the live Flight 16 road
      const kind = beatKind(g);
      const box = ["return_engines", "engines", "engines_ahead"].includes(kind) ? "raptor" : "cryo";
      const beat = beats.find((b) => b.vehicleId === veh && b.kindEvent === kind && (g.some((f) => f.url && f.url === b.url) || String(b.at).slice(0, 10) === ((eventDateOf(g) && eventDateOf(g).iso) || "")));
      const date = eventDateOf(g);
      const link = primaryLink(g, isMilestoneKind(kind) ? kind : null, { vehicle: veh, flight: flightGuess(veh), date, kind });
      const text = tidyPlace((beat && beat.text) || beatText(g, kind, {}));
      const live = g.find((f) => f.liveEntry && (f.liveBox === box || (box === "raptor" && f.liveBox === "cryo")));
      const photos = (beat && (beat.media_override || beat.x_post || beat.image || beat.keep_image)) ? photoFields(beat) : bestPhotoFromGroup(g, livePhotos, veh, date, ["return_engines", "engines", "engines_ahead"].includes(kind) ? "raptor" : "cryo");
      const tm = beat ? { at: beat.at, time_known: beat.time_known } : beatTimeMeta(g, link, date);
      let entry;
      if (live && live.liveEntry) {
        entry = live.liveEntry;
        if (entry.text !== text) { entry.text = text; entry.x_text = text; changed = true; }
        if (date && entry.date !== fmtDay(date)) { entry.date = fmtDay(date); changed = true; }
        if (tm.time_known === false) {
          entry.time_known = false;
          if (date && entry.at && ukDate(entry.at) && ukDate(entry.at).iso !== date.iso) { entry.at = date.iso; changed = true; }
        } else if (date && entry.at && ukDate(entry.at) && ukDate(entry.at).iso !== date.iso) {
          entry.at = tm.at || date.iso;
          changed = true;
        }
        if (link && link.url) entry.url = entry.url || link.url;
        if (kind === "cryo_complete") entry.complete = true;
        entry.hardware = entry.hardware || veh;
      } else {
        entry = {
          id: "review-" + (link && ((link.url || "").split("/").pop() || link.id) || g[0].id),
          date: fmtDay(date),
          at: tm.time_known && link && link.publishedMs ? new Date(link.publishedMs).toISOString() : (date ? date.iso : undefined),
          time_known: tm.time_known,
          text, x_text: text, src: link ? ("@" + (link.handle || "").replace(/^@/, "")) : undefined,
          source: link ? displaySource(link) : undefined, review_source: link ? displaySource(link) : undefined, url: link && link.url, trust: "trusted",
          no_push: true, tier: link && link.tier === 1 ? 1 : 2, hardware: veh, stage: box,
          complete: kind === "cryo_complete" || undefined
        };
        changed = true;
        log(`review: new ${box} ${veh} ${entry.date}: ${text.slice(0, 90)}`);
      }
      attachPhotos(entry, photos);
      if (box === "raptor") applyRaptorDefaultPhoto(entry);
      if (link && !entry.review_source) entry.review_source = displaySource(link);
      byBox[box].push({ entry, veh, at: Date.parse(entry.at || "") || 0, kind });
    }
    for (const box of ["cryo", "raptor"]) {
      const cat = (road.categories || []).find((c) => c.id === box);
      if (!cat) continue;
      const reviewedVeh = new Set(byBox[box].map((x) => x.veh));
      const keepOther = (cat.history || []).filter((h) => {
        const hw = String(h.hardware || "").replace(/^Booster\s*/i, "B").replace(/^Ship\s*/i, "S");
        if (h.kind === "check") return false;
        if (reviewedVeh.has(hw)) return byBox[box].some((x) => x.entry === h);
        // Drop current-vehicle leftovers that we refiled to the other box
        if (current.has(hw) && byBox[box === "cryo" ? "raptor" : "cryo"].some((x) => x.entry === h)) return false;
        if (current.has(hw) && !byBox[box].some((x) => x.entry === h) && (hw === "B23" || hw === "S43")) return false;
        return true;
      });
      const hist = [];
      const ids = new Set();
      for (const h of [...byBox[box].map((x) => x.entry), ...keepOther]) {
        if (h.id && ids.has(h.id)) continue;
        if (h.id) ids.add(h.id);
        hist.push(h);
      }
      hist.sort((a, b) => (Date.parse(b.at || "") || 0) - (Date.parse(a.at || "") || 0));
      cat.history = hist;
    }
    // Refile any leftover "for engine installation" still sitting in cryo
    const cryo = (road.categories || []).find((c) => c.id === "cryo");
    const rap = (road.categories || []).find((c) => c.id === "raptor");
    if (cryo && rap) {
      cryo.history = (cryo.history || []).filter((h) => {
        if (RETURN_ENGINES.test(h.text || "")) {
          if (!(rap.history || []).some((x) => x.id === h.id)) rap.history = [h, ...(rap.history || [])];
          log(`review: refiled ${h.id} cryo → raptor`);
          return false;
        }
        return true;
      });
    }
    return changed;
  }

  function writeArchive(road, pills, beats, facts, log) {
    const arch = road.archive && road.archive["15"];
    if (!arch) return false;
    let changed = false;
    if (Array.isArray(arch.entries)) {
      const before = arch.entries.length;
      arch.entries = arch.entries.filter((e) => !(e.box === "cryo" && /Ship 42/.test((e.text || "") + (e.vehicle || "")) && /27 Oct/.test(e.date || "") && MORE_CRYO.test(e.text || "")));
      if (arch.entries.length !== before) { changed = true; log("review: dropped stale S42 27 Oct cryo archive row"); }
    }
    // Past-flight Roads keep production's compact archive summary (no pill rewrite).
    return changed;
  }

  function pillsFor(road, box) {
    const list = ((road.review && road.review.pills) || []).filter((p) => !box || p.box === box);
    list.sort((a, b) => {
      const va = /^Ship/.test(a.vehicle) ? 0 : /^Booster/.test(a.vehicle) ? 1 : 2;
      const vb = /^Ship/.test(b.vehicle) ? 0 : /^Booster/.test(b.vehicle) ? 1 : 2;
      if (va !== vb) return va - vb;
      return String(b.endAt || b.at).localeCompare(String(a.endAt || a.at));
    });
    return list;
  }
  function grouped(pills) {
    const groups = [];
    for (const p of pills || []) {
      const last = groups[groups.length - 1];
      if (last && last.vehicle === p.vehicle) last.items.push(p);
      else groups.push({ vehicle: p.vehicle, items: [p] });
    }
    return groups;
  }
  function isCleanText(s) {
    const t = String(s || "");
    if (/APP MISREAD|PARTLY OPEN|\bDATA_FIX\b|assumed_reason|inferred from|so all \d+ Raptors are installed|source-merge|\+N sources/.test(t)) return false;
    if (/\bPASS\b/.test(t) && !/pass\./i.test(t)) return false;
    if (t.includes("?")) return false;
    return true;
  }
  function renderedTexts(road) {
    const out = [];
    for (const p of (road.review && road.review.pills) || []) out.push(p.label, p.text, p.vehicle);
    for (const b of (road.review && road.review.beats) || []) out.push(b.date, b.text, b.vehicle, b.source);
    for (const c of road.categories || []) for (const h of c.history || []) {
      if (h.kind === "check") continue;
      out.push(h.text, h.card_text, h.log_text);
      for (const u of h.updates || []) out.push(u.text);
    }
    for (const f of road.feed_items || []) {
      if (f.card_hide) continue;
      const body = f.body || f.text || "";
      if (/\b(?:Ship|Booster)\s+\d+\b/.test(body)) out.push(body);
    }
    return out.filter(Boolean);
  }

