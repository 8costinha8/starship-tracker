  function detectVehicle(e, box, road) {
    if (e.vehicle && /^(Ship|Booster)\s+\d+$/i.test(e.vehicle)) {
      const name = e.vehicle.replace(/\bship\b/i, "Ship").replace(/\bbooster\b/i, "Booster");
      return { id: vehIdOfName(name), name };
    }
    const t = `${e.text || ""} ${e.card_text || ""} ${e.hardware || ""}`;
    const m = t.match(/\b(Ship|Booster)\s+(\d+)\b/i);
    if (m) {
      const name = (m[1][0].toUpperCase() === "S" ? "Ship " : "Booster ") + m[2];
      return { id: vehIdOfName(name), name };
    }
    const hw = String(e.hardware || "").replace(/^Booster\s*/i, "B").replace(/^Ship\s*/i, "S");
    if (/^[SB]\d+$/i.test(hw)) return { id: hw.toUpperCase(), name: vName(hw) };
    if (box === "pad") return { id: "PAD", name: road.pad || "Pad 2" };
    if (box === "faa") return { id: "FAA", name: "FAA licence" };
    if (box === "date") return { id: "DATE", name: "Launch date" };
    return null;
  }
  function inFlightScope(vehId, road, flight) {
    if (vehId === "PAD" || vehId === "FAA" || vehId === "DATE") return true;
    const vs = new Set();
    if (flight === road.flight) for (const v of road.vehicles || []) vs.add(String(v).toUpperCase());
    const arch = road.archive && road.archive[String(flight)];
    if (arch && arch.summary) {
      for (const it of arch.summary.items || []) {
        const id = vehIdOfName(it.vehicle);
        if (/^[SB]\d+$/.test(id)) vs.add(id);
      }
    }
    if (flight === 15) { vs.add("S42"); vs.add("B22"); }
    if (flight === 14) { vs.add("S41"); vs.add("B21"); }
    return vs.has(String(vehId).toUpperCase());
  }
